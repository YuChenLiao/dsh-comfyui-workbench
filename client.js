    /**
     * 计算「追加一页」之后列表长什么样、还要不要继续拉。
     *
     * 抽成纯函数是为了把两个停手条件钉死：
     *   - 本批没有新条目（offset 分页在列表变动后会重复拉到同一段）→ 停；
     *   - 已经够到 total → 停。
     * 只要有一条没守住，哨兵可见时就会无限重发请求，底部视图就会抖。
     * @param {Array<{ path: string }>} baseItems 当前已加载的条目。
     * @param {Array<{ path: string }>} batch 这一批返回的条目。
     * @param {number} offset 本次请求的偏移量。
     * @param {number} total 服务端报告的总数。
     * @returns {{ items: Array<object>, more: boolean }} 合并后的列表与是否还有更多。
     */
    function planPage(baseItems, batch, offset, total) {
      const seen = new Set(baseItems.map(entry => entry.path))
      const appended = []
      for (const entry of batch) {
        if (seen.has(entry.path)) continue
        seen.add(entry.path)
        appended.push(entry)
      }
      return {
        items: baseItems.concat(appended),
        more: appended.length > 0 && offset + batch.length < total,
      }
    }

